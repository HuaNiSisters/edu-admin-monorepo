BEGIN;

ALTER TABLE public."PaymentFollowUp"
  ADD COLUMN follow_up_id integer GENERATED BY DEFAULT AS IDENTITY,
  DROP CONSTRAINT "PaymentFollowUp_pkey",
  ADD CONSTRAINT "PaymentFollowUp_pkey" PRIMARY KEY (follow_up_id);

CREATE INDEX payment_follow_up_payment_idx
  ON public."PaymentFollowUp" (payment_id);
CREATE UNIQUE INDEX payment_follow_up_one_open_per_payment_idx
  ON public."PaymentFollowUp" (payment_id) WHERE NOT is_completed;

CREATE FUNCTION public.sync_edited_payment_follow_up() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NEW.follow_up_date IS NULL THEN
    DELETE FROM public."PaymentFollowUp"
    WHERE payment_id = NEW.payment_id AND NOT is_completed;
  ELSE
    INSERT INTO public."PaymentFollowUp" (payment_id, due_date)
    VALUES (NEW.payment_id, NEW.follow_up_date)
    ON CONFLICT (payment_id) WHERE NOT is_completed
    DO UPDATE SET due_date = EXCLUDED.due_date;
  END IF;

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.sync_edited_payment_follow_up() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER payment_follow_up_after_date_change
  AFTER UPDATE OF follow_up_date ON public."Payment"
  FOR EACH ROW WHEN (OLD.follow_up_date IS DISTINCT FROM NEW.follow_up_date)
  EXECUTE FUNCTION public.sync_edited_payment_follow_up();

COMMIT;
